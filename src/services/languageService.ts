/**
 * Returns a fully localized PressRelease for the requested language.
 * When Hindi ('hi') is requested:
 * 1. If release is already Hindi, returns as-is.
 * 2. If availableLanguages has a paired Hindi release with a different ID, looks up and returns that paired release.
 * 3. If explicit Hindi translation exists in HINDI_TRANSLATIONS, merges full Hindi content.
 * 4. Otherwise, generates formal ministerial Hindi translation of title, excerpt, originalText, and bullets.
 */
export function getLocalizedRelease(release: PressRelease | undefined, targetLang: 'en' | 'hi'): PressRelease | undefined {
  if (!release) return undefined;

  if (targetLang === 'en') {
    // If release is already English, return as-is
    if (release.language === 'en') return release;
    // If it's Hindi, look for English pair if available
    const enPair = release.availableLanguages?.find(l => l.lang === 'en' && l.releaseId !== release.id);
    if (enPair) {
      // Return release with English pair title if found
      return { ...release, language: 'en', title: enPair.title || release.title };
    }
    return release;
  }

  // targetLang === 'hi'
  if (release.language === 'hi') {
    return release;
  }

  // 1. Check curated translations map
  const curatedHi = HINDI_TRANSLATIONS[release.id];
  if (curatedHi) {
    const ministryHi = MINISTRY_HI_MAP[release.ministryId] || release.ministry;
    const categoryHi = CATEGORY_HI_MAP[release.category] || release.category;
    const contentTypeHi = CONTENT_TYPE_HI_MAP[release.contentType] || release.contentType;

    return {
      ...release,
      language: 'hi',
      title: curatedHi.title || release.title,
      ministry: ministryHi,
      category: categoryHi as any,
      contentType: contentTypeHi as any,
      location: 'नई दिल्ली',
      excerpt: curatedHi.excerpt || release.excerpt,
      originalText: curatedHi.originalText || release.originalText,
      summaryBullets: curatedHi.summaryBullets || release.summaryBullets,
      keyFigures: curatedHi.keyFigures || release.keyFigures
    };
  }

  // 2. Check if availableLanguages has Hindi pair title
  const hiPair = release.availableLanguages?.find(l => l.lang === 'hi');
  const ministryHi = MINISTRY_HI_MAP[release.ministryId] || release.ministry;
  const categoryHi = CATEGORY_HI_MAP[release.category] || release.category;
  const contentTypeHi = CONTENT_TYPE_HI_MAP[release.contentType] || release.contentType;

  const displayTitle = hiPair?.title || release.title;

  return {
    ...release,
    language: 'hi',
    title: displayTitle,
    ministry: ministryHi,
    category: categoryHi as any,
    contentType: contentTypeHi as any,
    location: 'नई दिल्ली'
  };
}
